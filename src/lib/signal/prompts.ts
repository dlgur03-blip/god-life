// Tomorrow Signal - AI Analysis Prompts (Step 1~4 Pipeline)

export function getDateContext(now: Date = new Date()) {
  const kst = new Date(now.getTime() + 9 * 60 * 60 * 1000);
  const year = kst.getFullYear();
  const month = kst.getMonth() + 1;
  const day = kst.getDate();
  const hours = kst.getHours();
  const minutes = kst.getMinutes();
  const dayNames = ['일', '월', '화', '수', '목', '금', '토'];
  const dayOfWeek = dayNames[kst.getDay()];

  return {
    dateStr: `${year}년 ${month}월 ${day}일 (${dayOfWeek})`,
    timeStr: `${hours}시 ${minutes}분`,
    fullStr: `한국 ${year}년 ${month}월 ${day}일 ${hours}시 ${minutes}분`,
    isoDate: kst.toISOString().slice(0, 10),
  };
}

